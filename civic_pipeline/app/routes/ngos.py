import logging
from typing import List, Optional
from uuid import UUID
from fastapi import APIRouter, HTTPException, status

from ..database import get_repository
from ..models.schemas import (
    NGOActionableFeedItem,
    CivicIssueOut,
    NGOVolunteerEventOut,
    SeverityLevel,
)

logger = logging.getLogger("civic_pipeline.routes.ngos")
router = APIRouter(prefix="/api/ngos", tags=["NGO Dashboard & Feed"])

SEVERITY_WEIGHTS = {
    "Critical": 40.0,
    "High": 30.0,
    "Medium": 20.0,
    "Low": 10.0,
}


@router.get(
    "/{ngo_id}/actionable-feed",
    response_model=List[NGOActionableFeedItem],
    summary="Get verified civic issues matching NGO operating wards and focus categories"
)
async def get_ngo_actionable_feed(ngo_id: UUID) -> List[NGOActionableFeedItem]:
    """
    Returns verified civic issues matching the specified NGO's operating wards and primary causes.
    Results are prioritized and sorted by combined severity weighting and authenticity score.
    Includes ready-to-publish draft volunteer events generated by the AI mobilization engine.
    """
    repo = get_repository()
    nid_str = str(ngo_id)
    ngo = repo.get_ngo(nid_str)
    if not ngo:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Registered NGO with ID '{ngo_id}' not found."
        )

    operating_wards = set(ngo.get("operating_wards", []))
    primary_causes = set(ngo.get("primary_causes", []))

    feed_items: List[NGOActionableFeedItem] = []

    # Iterate through issues to find verified matches
    # In live Supabase this is backed by an indexed SQL query
    candidate_issues = []
    if hasattr(repo, "issues"):
        candidate_issues = list(repo.issues.values())
    else:
        # Live Supabase query
        resp = repo.client.table("civic_issues")\
            .select("*")\
            .gte("authenticity_score", 65)\
            .execute()
        candidate_issues = resp.data or []

    for issue in candidate_issues:
        ward = issue.get("ward")
        category = issue.get("category")
        authenticity = issue.get("authenticity_score", 0)

        # Must match NGO's operational boundary and domain
        if ward not in operating_wards or category not in primary_causes:
            continue

        # Must meet minimum verification threshold
        if authenticity < 65 and issue.get("status") not in ("verified_pending_ngo", "event_active"):
            continue

        issue_id = str(issue["id"])

        # Fetch draft event for this NGO and issue, if available
        existing_events = [
            e for e in repo.get_events_by_issue(issue_id)
            if str(e.get("ngo_id")) == nid_str
        ]
        draft_out: Optional[NGOVolunteerEventOut] = None
        if existing_events:
            ev = existing_events[0]
            draft_out = NGOVolunteerEventOut(
                id=UUID(ev["id"]),
                issue_id=UUID(ev["issue_id"]),
                ngo_id=UUID(ev["ngo_id"]),
                event_title=ev["event_title"],
                event_date=ev["event_date"],
                meeting_point=ev["meeting_point"],
                target_volunteers=ev["target_volunteers"],
                registered_volunteers=ev.get("registered_volunteers", 0),
                required_gear=ev.get("required_gear", []),
                tasks_breakdown=ev.get("tasks_breakdown", []),
                safety_guidelines=ev.get("safety_guidelines", []),
                status=ev["status"],
                created_at=ev.get("created_at"),
                updated_at=ev.get("updated_at")
            )

        # Compute priority score: severity weight + (authenticity_score * 0.6)
        sev_weight = SEVERITY_WEIGHTS.get(issue.get("severity", "Medium"), 20.0)
        priority_score = round(sev_weight + (authenticity * 0.6), 2)

        issue_out = CivicIssueOut(
            id=UUID(issue["id"]),
            title=issue["title"],
            summary=issue["summary"],
            category=issue["category"],
            ward=issue["ward"],
            latitude=issue["latitude"],
            longitude=issue["longitude"],
            severity=issue["severity"],
            authenticity_score=authenticity,
            verification_reasoning=issue.get("verification_reasoning"),
            responsible_authority=issue["responsible_authority"],
            source_count=issue.get("source_count", 1),
            status=issue.get("status", "verified_pending_ngo"),
            created_at=issue["created_at"],
            updated_at=issue.get("updated_at")
        )

        feed_items.append(
            NGOActionableFeedItem(
                issue=issue_out,
                event_draft=draft_out,
                recommended_priority_score=priority_score
            )
        )

    # Sort descending by priority score
    feed_items.sort(key=lambda x: x.recommended_priority_score, reverse=True)
    return feed_items
