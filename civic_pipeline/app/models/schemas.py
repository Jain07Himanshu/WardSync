from datetime import datetime, date, timezone
from enum import Enum
from typing import List, Optional, Dict, Any
from uuid import UUID, uuid4
from pydantic import BaseModel, Field, field_validator


# ============================================================================
# Core Enums
# ============================================================================

class SourceType(str, Enum):
    TWITTER = "twitter"
    NEWS = "news"
    RESIDENT_COMPLAINT = "resident_complaint"
    MUNICIPAL_NOTICE = "municipal_notice"


class CivicCategory(str, Enum):
    SANITATION = "Sanitation"
    ROADS_AND_TRANSIT = "Roads & Transit"
    WATERLOGGING = "Waterlogging"
    PUBLIC_SAFETY = "Public Safety"
    ENVIRONMENT = "Environment"


class SeverityLevel(str, Enum):
    LOW = "Low"
    MEDIUM = "Medium"
    HIGH = "High"
    CRITICAL = "Critical"


class IssueStatus(str, Enum):
    FLAGGED_UNVERIFIED = "flagged_unverified"
    VERIFIED_PENDING_NGO = "verified_pending_ngo"
    EVENT_ACTIVE = "event_active"
    RESOLVED = "resolved"


class EventStatus(str, Enum):
    DRAFT = "draft"
    PUBLISHED = "published"
    COMPLETED = "completed"


# ============================================================================
# AI Extraction & Verification Pydantic Schemas (Structured Output)
# ============================================================================

class Coordinates(BaseModel):
    """Geographical coordinates representing the problem location."""
    latitude: float = Field(..., description="Latitude coordinate between -90 and 90")
    longitude: float = Field(..., description="Longitude coordinate between -180 and 180")


class SuggestedActionBlueprint(BaseModel):
    """Initial volunteer mobilization action framework generated by AI."""
    event_title: str = Field(..., description="Action-oriented title for citizen mobilization event")
    required_gear: List[str] = Field(
        default_factory=list,
        description="List of tools, protective gear, or materials required (e.g. gloves, shovels, boots)"
    )
    tasks_breakdown: List[str] = Field(
        default_factory=list,
        description="Step-by-step tasks volunteers will undertake"
    )
    safety_guidelines: List[str] = Field(
        default_factory=list,
        description="Critical safety rules, hazards to avoid, and emergency measures"
    )


class CivicVerificationResult(BaseModel):
    """
    Structured output schema for Google Gemini 1.5 Flash extraction and authenticity verification.
    """
    title: str = Field(..., description="Concise, factual title of the civic failure")
    summary: str = Field(..., description="Synthesized description summarizing the problem context and evidence")
    category: CivicCategory = Field(..., description="Categorized civic domain")
    ward: str = Field(..., description="Locality or municipal administrative ward name (e.g. Koramangala Ward 151)")
    coordinates: Coordinates = Field(..., description="Approximate latitude and longitude")
    severity: SeverityLevel = Field(..., description="Severity level: Low, Medium, High, or Critical")
    responsible_authority: str = Field(
        ...,
        description="Specific municipal department in charge (e.g. BBMP Solid Waste Management, Municipal Water Supply & Drainage Board)"
    )
    authenticity_score: int = Field(
        ...,
        ge=0,
        le=100,
        description="Authenticity score from 0 to 100 based on cross-source consistency, concrete location indicators, temporal freshness, and lack of sensationalism/spam"
    )
    authenticity_breakdown: str = Field(
        ...,
        description="Detailed rationale explaining why the authenticity score was assigned, citing supporting signals"
    )
    suggested_action_blueprint: SuggestedActionBlueprint = Field(
        ...,
        description="Pre-packaged volunteer mobilization framework"
    )


# ============================================================================
# API Request & Ingestion Schemas
# ============================================================================

class RawSignalInput(BaseModel):
    """Input payload for a single civic signal."""
    source_type: SourceType
    source_url: Optional[str] = None
    raw_content: str = Field(..., min_length=5, description="Raw text snippet, tweet, complaint, or news article")
    published_at: Optional[datetime] = Field(default_factory=lambda: datetime.now(timezone.utc))


class MultiSourceIngestRequest(BaseModel):
    """Batch ingestion request payload."""
    signals: List[RawSignalInput] = Field(..., min_length=1, description="List of multi-source problem signals")


# ============================================================================
# Database & Domain Entity Schemas
# ============================================================================

class CivicSourceOut(BaseModel):
    id: UUID
    issue_id: Optional[UUID] = None
    source_type: SourceType
    source_url: Optional[str] = None
    raw_content: str
    published_at: datetime
    status: str
    created_at: datetime


class CivicIssueOut(BaseModel):
    id: UUID
    title: str
    summary: str
    category: CivicCategory
    ward: str
    latitude: float
    longitude: float
    severity: SeverityLevel
    authenticity_score: int
    verification_reasoning: Optional[str] = None
    responsible_authority: str
    source_count: int
    status: IssueStatus
    created_at: datetime
    updated_at: Optional[datetime] = None


class NGOOut(BaseModel):
    id: UUID
    name: str
    primary_causes: List[str]
    operating_wards: List[str]
    contact_email: str
    is_verified: bool
    created_at: Optional[datetime] = None


class NGOVolunteerEventOut(BaseModel):
    id: UUID
    issue_id: UUID
    ngo_id: UUID
    event_title: str
    event_date: date
    meeting_point: str
    target_volunteers: int
    registered_volunteers: int = 0
    required_gear: List[str]
    tasks_breakdown: List[str]
    safety_guidelines: List[str]
    status: EventStatus
    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None


# ============================================================================
# NGO Dispatch & Actionable Feed Schemas
# ============================================================================

class AlertPayload(BaseModel):
    """Real-time alert notification payload pushed to matching NGOs."""
    ngo_id: UUID
    ngo_name: str
    issue_id: UUID
    issue_title: str
    category: CivicCategory
    ward: str
    severity: SeverityLevel
    authenticity_score: int
    evidence_summary: str
    prepackaged_event_id: UUID
    suggested_action_blueprint: SuggestedActionBlueprint


class IngestPipelineResult(BaseModel):
    """Comprehensive pipeline execution outcome returned by POST /api/ingest/multi-source."""
    ingested_source_count: int
    sources: List[CivicSourceOut]
    issue: CivicIssueOut
    cluster_action: str = Field(..., description="'merged_existing_cluster' or 'created_new_issue'")
    similarity_score: Optional[float] = None
    authenticity_score: int
    dispatched_events: List[NGOVolunteerEventOut] = Field(default_factory=list)
    ngo_alerts: List[AlertPayload] = Field(default_factory=list)


class NGOActionableFeedItem(BaseModel):
    """Individual item returned in the NGO actionable feed."""
    issue: CivicIssueOut
    event_draft: Optional[NGOVolunteerEventOut] = None
    recommended_priority_score: float = Field(
        ...,
        description="Computed priority combining severity weight and authenticity score"
    )


# ============================================================================
# Event Publishing & Map Cluster Schemas
# ============================================================================

class EventPublishRequest(BaseModel):
    """Payload sent by NGO to review, adjust, and publish a volunteer event."""
    event_id: UUID
    ngo_id: UUID
    event_title: Optional[str] = None
    event_date: Optional[date] = None
    meeting_point: Optional[str] = None
    target_volunteers: Optional[int] = Field(None, gt=0)
    required_gear: Optional[List[str]] = None
    tasks_breakdown: Optional[List[str]] = None
    safety_guidelines: Optional[List[str]] = None


class PublicEventSummary(BaseModel):
    event_id: UUID
    ngo_id: UUID
    ngo_name: str
    event_title: str
    event_date: date
    meeting_point: str
    target_volunteers: int
    registered_volunteers: int
    required_gear: List[str]
    tasks_breakdown: List[str]
    safety_guidelines: List[str]
    status: EventStatus


class PublicMapClusterOut(BaseModel):
    """Public map issue cluster with active citizen volunteer events."""
    issue_id: UUID
    title: str
    summary: str
    category: CivicCategory
    ward: str
    latitude: float
    longitude: float
    severity: SeverityLevel
    authenticity_score: int
    responsible_authority: str
    source_count: int
    status: IssueStatus
    active_events: List[PublicEventSummary]
